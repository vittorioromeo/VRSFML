#if __has_builtin(__is_reference)

    ////////////////////////////////////////////////////////////
    #define ZB_IS_REFERENCE(...) __is_reference(__VA_ARGS__)

#else

////////////////////////////////////////////////////////////
// Headers
////////////////////////////////////////////////////////////
    #include <type_traits>


    ////////////////////////////////////////////////////////////
    #define ZB_IS_REFERENCE(...) ::std::is_reference_v<__VA_ARGS__>

#endif


namespace zb
{
////////////////////////////////////////////////////////////
template <typename T>
inline constexpr bool isReference = ZB_IS_REFERENCE(T);

} // namespace zb
