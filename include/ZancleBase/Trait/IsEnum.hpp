#if __has_builtin(__is_enum)

    ////////////////////////////////////////////////////////////
    #define ZB_IS_ENUM(...) __is_enum(__VA_ARGS__)

#else

////////////////////////////////////////////////////////////
// Headers
////////////////////////////////////////////////////////////
    #include <type_traits>


    ////////////////////////////////////////////////////////////
    #define ZB_IS_ENUM(...) ::std::is_enum_v<__VA_ARGS__>

#endif


namespace zb
{
////////////////////////////////////////////////////////////
template <typename T>
inline constexpr bool isEnum = ZB_IS_ENUM(T);

} // namespace zb
