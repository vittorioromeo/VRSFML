#if __has_builtin(__is_trivial)

    ////////////////////////////////////////////////////////////
    #define ZB_IS_TRIVIAL(...) __is_trivial(__VA_ARGS__)

#else

////////////////////////////////////////////////////////////
// Headers
////////////////////////////////////////////////////////////
    #include <type_traits>


    ////////////////////////////////////////////////////////////
    #define ZB_IS_TRIVIAL(...) ::std::is_trivial_v<__VA_ARGS__>

#endif


namespace zb
{
////////////////////////////////////////////////////////////
template <typename T>
inline constexpr bool isTrivial = ZB_IS_TRIVIAL(T);

} // namespace zb
