#if __has_builtin(__add_pointer)

    ////////////////////////////////////////////////////////////
    #define ZB_ADD_POINTER(...) __add_pointer(__VA_ARGS__)

#else

////////////////////////////////////////////////////////////
// Headers
////////////////////////////////////////////////////////////
    #include "ZancleBase/Trait/VoidT.hpp"


namespace zb::priv
{
////////////////////////////////////////////////////////////
template <typename T, typename = void>
struct AddPointerHelper
{
    using type = T;
};


////////////////////////////////////////////////////////////
template <typename T>
struct AddPointerHelper<T, VoidT<T*>>
{
    using type = T*;
};


////////////////////////////////////////////////////////////
template <typename T>
struct AddPointer : public AddPointerHelper<T>
{
};


////////////////////////////////////////////////////////////
template <typename T>
struct AddPointer<T&>
{
    using type = T*;
};


////////////////////////////////////////////////////////////
template <typename T>
struct AddPointer<T&&>
{
    using type = T*;
};

} // namespace zb::priv

    ////////////////////////////////////////////////////////////
    #define ZB_ADD_POINTER(...) typename ::zb::priv::AddPointer<__VA_ARGS__>::type

#endif


namespace zb
{
////////////////////////////////////////////////////////////
template <typename T>
using AddPointer = ZB_ADD_POINTER(T);

} // namespace zb
